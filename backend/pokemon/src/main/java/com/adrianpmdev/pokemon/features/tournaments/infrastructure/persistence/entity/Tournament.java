package com.adrianpmdev.pokemon.features.tournaments.infrastructure.persistence.entity;

import com.adrianpmdev.pokemon.features.games.infrastructure.persistence.entity.Game;
import com.adrianpmdev.pokemon.features.lockes.infrastructure.persistence.entity.Locke;
import com.adrianpmdev.pokemon.features.tournaments.domain.TournamentFormat;
import com.adrianpmdev.pokemon.features.tournaments.domain.TournamentStatus;
import com.adrianpmdev.pokemon.features.tournaments.infrastructure.persistence.converter.EnumConverters;
import jakarta.persistence.Column;
import jakarta.persistence.Convert;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.time.Instant;
import java.util.UUID;

/**
 * A tournament of a randomlocke, played in one game. Every series is best of 3.
 *
 * @author adrianpmdev
 */
@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "tournaments", schema = "pokemon")
public class Tournament {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "locke_id", nullable = false)
    private Locke locke;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "game_id", nullable = false)
    private Game game;

    /** Order inside the randomlocke (1, 2, 3...). The cumulative standings follow it. */
    @Column(nullable = false)
    private short position;

    @Column(length = 100, nullable = false)
    private String name;

    @Column(length = 1000)
    private String description;

    @Convert(converter = EnumConverters.FormatConverter.class)
    @Column(length = 20, nullable = false)
    private TournamentFormat format;

    @Convert(converter = EnumConverters.StatusConverter.class)
    @Column(length = 20, nullable = false)
    private TournamentStatus status = TournamentStatus.DRAFT;

    @Column(name = "points_per_win", nullable = false)
    private short pointsPerWin = 1;

    /** Until this moment players only see their own team picture. */
    @Column(name = "teams_reveal_at")
    private Instant teamsRevealAt;

    /**
     * Size of the bracket generated by the app. Null when there is no bracket, or for imported brackets,
     * which are shown as they were played and never re-seeded.
     */
    @Column(name = "bracket_size")
    private Short bracketSize;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @PrePersist
    void onCreate() {
        createdAt = Instant.now();
    }

    /**
     * Whether players can already see every team picture.
     *
     * @param now current instant
     * @return true when there is no reveal moment or it has passed
     */
    public boolean teamsRevealed(Instant now) {
        return teamsRevealAt == null || !now.isBefore(teamsRevealAt);
    }
}
